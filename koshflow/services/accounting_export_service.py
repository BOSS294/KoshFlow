from __future__ import annotations

from datetime import datetime
from pathlib import Path
from xml.sax.saxutils import escape
from zoneinfo import ZoneInfo

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT, TA_RIGHT, TA_CENTER
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import Image as RLImage, LongTable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from koshflow.core.database import Database
from koshflow.services.business_service import BusinessService
from koshflow.services.invoice_profile_service import load_invoice_profile
from koshflow.services.pdf_service import _cropped_logo_stream

ACCENT = colors.HexColor("#C9E86A")
INK = colors.HexColor("#20231D")
MUTED = colors.HexColor("#646B60")
GRID = colors.HexColor("#D9DED1")
PAPER_ALT = colors.HexColor("#F7F8F3")
IST = ZoneInfo("Asia/Kolkata")


def _font_pair() -> tuple[str, str]:
    candidates = [
        (Path("C:/Windows/Fonts/segoeui.ttf"), Path("C:/Windows/Fonts/segoeuib.ttf")),
        (Path("C:/Windows/Fonts/arial.ttf"), Path("C:/Windows/Fonts/arialbd.ttf")),
        (Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"), Path("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf")),
        (Path("/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf"), Path("/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf")),
    ]
    names = set(pdfmetrics.getRegisteredFontNames())
    for regular, bold in candidates:
        if regular.exists():
            try:
                if "KoshReport" not in names:
                    pdfmetrics.registerFont(TTFont("KoshReport", str(regular)))
                if bold.exists() and "KoshReport-Bold" not in names:
                    pdfmetrics.registerFont(TTFont("KoshReport-Bold", str(bold)))
                return "KoshReport", "KoshReport-Bold" if bold.exists() else "Helvetica-Bold"
            except Exception:
                continue
    return "Helvetica", "Helvetica-Bold"


def _clean(value: object) -> str:
    # Escape user-entered narration and descriptions so markup can never break a PDF.
    return escape(str(value if value is not None else "")).replace("\n", "<br/>")


def _column_weights(headers: list[str]) -> list[float]:
    weights: list[float] = []
    for header in headers:
        key = header.casefold()
        if any(word in key for word in ("narration", "description", "particular", "counterpart", "account", "customer", "supplier", "reference")):
            weights.append(2.25 if "narration" in key or "description" in key or "particular" in key else 1.65)
        elif any(word in key for word in ("amount", "balance", "debit", "credit", "total", "tax", "value", "inflow", "outflow", "qty", "quantity", "rate", "paid")):
            weights.append(0.9)
        else:
            weights.append(1.1)
    return weights


def generate_accounting_report_pdf(
    database: Database,
    business_id: str,
    output_path: str | Path,
    title: str,
    subtitle: str,
    headers: list[str],
    rows: list[list[object]],
) -> Path:
    """Write a branded, multi-page PDF report from the exact rows being exported."""
    if not headers:
        raise ValueError("A report must have at least one column.")
    target = Path(output_path).expanduser().resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    profile = BusinessService(database).get_profile(business_id)
    invoice = load_invoice_profile(database, business_id)
    regular, bold = _font_pair()
    wide = len(headers) >= 6
    page_size = landscape(A4) if wide else A4
    margin_x = 12 * mm if wide else 16 * mm
    doc = SimpleDocTemplate(
        str(target), pagesize=page_size, leftMargin=margin_x, rightMargin=margin_x,
        topMargin=17 * mm, bottomMargin=16 * mm,
        title=f"{title} - {profile.get('trade_name') or profile.get('legal_name') or 'Business'}",
        author=profile.get("trade_name") or profile.get("legal_name") or "KoshFlow",
        subject="Accounting report generated by KoshFlow",
    )
    styles = getSampleStyleSheet()
    name_style = ParagraphStyle("KoshReportBusiness", parent=styles["Normal"], fontName=bold, fontSize=14, leading=17, textColor=INK, spaceAfter=2)
    small_style = ParagraphStyle("KoshReportBusinessSmall", parent=styles["Normal"], fontName=regular, fontSize=7.5, leading=10, textColor=MUTED)
    title_style = ParagraphStyle("KoshReportTitle", parent=styles["Heading1"], fontName=bold, fontSize=18, leading=22, textColor=INK, spaceBefore=8, spaceAfter=3)
    sub_style = ParagraphStyle("KoshReportSubtitle", parent=styles["Normal"], fontName=regular, fontSize=8.5, leading=12, textColor=MUTED, spaceAfter=8)
    header_style = ParagraphStyle("KoshReportTableHeader", parent=styles["Normal"], fontName=bold, fontSize=7 if wide else 8, leading=9, textColor=INK, alignment=TA_LEFT)
    body_style = ParagraphStyle("KoshReportTableBody", parent=styles["Normal"], fontName=regular, fontSize=6.8 if wide else 8, leading=8.5 if wide else 10, textColor=INK)
    body_right = ParagraphStyle("KoshReportTableRight", parent=body_style, alignment=TA_RIGHT)
    address_parts = [profile.get("address", ""), profile.get("city", ""), profile.get("state", ""), profile.get("pincode", "")]
    address = ", ".join(str(x).strip() for x in address_parts if str(x or "").strip())
    contact = " · ".join(str(x).strip() for x in (profile.get("phone", ""), profile.get("email", ""), profile.get("gstin", "")) if str(x or "").strip())
    business_name = profile.get("trade_name") or profile.get("legal_name") or "Business"
    identity = [Paragraph(_clean(business_name), name_style)]
    for line in (address, contact, invoice.get("website", "")):
        if str(line or "").strip():
            identity.append(Paragraph(_clean(line), small_style))
    logo_flowable = None
    logo_path = Path(str(invoice.get("logo_path") or "")).expanduser() if invoice.get("logo_path") else None
    if logo_path and logo_path.is_file():
        prepared = _cropped_logo_stream(logo_path, 28 * mm, 16 * mm)
        if prepared:
            stream, width, height = prepared
            logo_flowable = RLImage(stream, width=width, height=height)
    if logo_flowable:
        logo_width = 32 * mm
        header = Table([[logo_flowable, identity]], colWidths=[logo_width, doc.width-logo_width], hAlign="LEFT")
    else:
        header = Table([[identity]], colWidths=[doc.width], hAlign="LEFT")
    header.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 2), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    line = Table([[""]], colWidths=[doc.width], rowHeights=[1.6*mm])
    line.setStyle(TableStyle([("BACKGROUND", (0,0), (-1,-1), ACCENT), ("BOX", (0,0), (-1,-1), 0, ACCENT)]))
    story: list[object] = [header, line, Paragraph(_clean(title), title_style), Paragraph(_clean(subtitle), sub_style)]
    if not rows:
        rows = [["No records for the selected period."] + [""] * (len(headers)-1)]
    # Fit each column into the printable width while giving names/narrations more room.
    weights = _column_weights(headers)
    available = doc.width
    widths = [available * w / sum(weights) for w in weights]
    header_cells = [Paragraph(_clean(h), header_style) for h in headers]
    data = [header_cells]
    numeric_terms = ("amount", "balance", "debit", "credit", "total", "tax", "value", "inflow", "outflow", "qty", "quantity", "rate", "paid")
    right_cols = {ix for ix, head in enumerate(headers) if any(term in head.casefold() for term in numeric_terms)}
    right_style = body_right
    for record in rows:
        cells = list(record[:len(headers)]) + [""] * max(0, len(headers)-len(record))
        data.append([Paragraph(_clean(value), right_style if ix in right_cols else body_style) for ix, value in enumerate(cells)])
    table = LongTable(data, colWidths=widths, repeatRows=1, hAlign="LEFT", splitByRow=1)
    style = [
        ("BACKGROUND", (0,0), (-1,0), ACCENT),
        ("TEXTCOLOR", (0,0), (-1,0), INK),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("BOX", (0,0), (-1,-1), 0.55, GRID),
        ("INNERGRID", (0,0), (-1,-1), 0.3, GRID),
        ("LEFTPADDING", (0,0), (-1,-1), 5), ("RIGHTPADDING", (0,0), (-1,-1), 5),
        ("TOPPADDING", (0,0), (-1,-1), 4 if wide else 5),
        ("BOTTOMPADDING", (0,0), (-1,-1), 4 if wide else 5),
        ("ROWBACKGROUNDS", (0,1), (-1,-1), [colors.white, PAPER_ALT]),
    ]
    for index, row in enumerate(rows, start=1):
        joined = " ".join(str(cell).casefold() for cell in row)
        if any(term in joined for term in ("grand total", "net profit", "gross profit", "total assets", "liabilities + equity", "total debit", "total credit", "closing cash", "total revenue", "total expenses")):
            style.extend([("FONTNAME", (0,index), (-1,index), bold), ("LINEABOVE", (0,index), (-1,index), 0.75, ACCENT)])
    table.setStyle(TableStyle(style))
    story.extend([Spacer(1, 3*mm), table, Spacer(1, 3*mm), Paragraph("Generated by KoshFlow · Verify this statement against source documents before statutory use.", small_style)])
    generated_at = datetime.now(IST).strftime("%d %b %Y, %I:%M %p IST")
    def on_page(canvas, report_doc):
        canvas.saveState()
        canvas.setStrokeColor(GRID)
        canvas.setLineWidth(0.4)
        canvas.line(margin_x, 11*mm, page_size[0]-margin_x, 11*mm)
        canvas.setFont(regular if regular in pdfmetrics.getRegisteredFontNames() else "Helvetica", 7)
        canvas.setFillColor(MUTED)
        canvas.drawString(margin_x, 7*mm, f"Generated by KoshFlow · {generated_at}")
        canvas.drawRightString(page_size[0]-margin_x, 7*mm, f"Page {report_doc.page}")
        canvas.restoreState()
    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return target
