import json

import pytest

from koshflow.services.theme_design import PRESETS, contrast_ratio, resolve_theme_design


def test_starter_presets_use_multiple_complete_layouts_and_cohesive_contrast():
    resolved = []
    for name, preset in PRESETS.items():
        template = {
            "template_name": name,
            "accent_color": {
                "KoshFlow Classic": "#C9E86A", "Mono Ledger": "#242720",
                "Olive Register": "#7F9147", "Forest Statement": "#315B43",
                "Cedar Paper": "#8C5A3C", "Burgundy Formal": "#7B3344",
                "Graphite Invoice": "#444841", "Ivory Trade": "#C7A96B",
                "Terracotta Sales": "#A85F48", "Evergreen Goods": "#2E6B57",
                "Sage Minimal": "#A6B89A", "Copper Contract": "#B27852",
                "Charcoal Modern": "#30332E", "Olive Compact": "#859447",
                "Cedar Compact": "#8C5A3C", "Market Receipt": "#C9E86A",
                "Clean Service": "#788C66", "Formal Estimate": "#6D7666",
                "Supplier Copy": "#B5A27D", "Night Ledger": "#575B51",
            }[name],
            "layout_json": "{}",
        }
        design = resolve_theme_design(template)
        colors = design["colors"]
        assert contrast_ratio(colors["text"], colors["page_bg"]) >= 4.5
        assert contrast_ratio(colors["muted"], colors["page_bg"]) >= 4.0
        assert contrast_ratio(colors["accent_text"], design["accent"]) >= 4.5
        assert design["style"] == preset["style"]
        resolved.append(design["style"])
    assert len(set(resolved)) >= 7
    night = resolve_theme_design({"template_name": "Night Ledger", "accent_color": "#575B51", "layout_json": "{}"})
    assert night["colors"]["page_bg"] == "#171916"
    assert contrast_ratio(night["colors"]["text"], night["colors"]["page_bg"]) >= 4.5


def test_custom_theme_automatically_corrects_inaccessible_text_colors():
    template = {
        "template_name": "Low Contrast Custom",
        "accent_color": "#FFFFFF",
        "layout_json": json.dumps({
            "style": "boxed",
            "colors": {
                "page_bg": "#FFFFFF", "text": "#FFFFFF", "muted": "#FDFDFD",
                "surface": "#FFFFFF", "border": "#EEEEEE", "accent_text": "#FFFFFF",
            },
        }),
    }
    design = resolve_theme_design(template)
    palette = design["colors"]
    assert contrast_ratio(palette["text"], palette["page_bg"]) >= 4.5
    assert contrast_ratio(palette["muted"], palette["page_bg"]) >= 4.0
    assert contrast_ratio(palette["accent_text"], design["accent"]) >= 4.5


def test_pdf_includes_generated_by_koshflow_attribution(database, tmp_path):
    pypdf = pytest.importorskip("pypdf")
    from koshflow.services.bill_service import BillService
    from koshflow.services.pdf_service import generate_invoice_pdf
    from koshflow.services.setup_service import SetupService
    from tests.helpers import valid_setup

    user_id, business_id = SetupService(database).complete_setup(valid_setup())
    service = BillService(database)
    service.ensure_starter_templates(business_id)
    bill_id = service.create_bill(business_id, user_id, {
        "customer_type": "B2C", "document_type": "tax_invoice", "customer_name": "Invoice Preview Customer",
        "invoice_date": "2026-10-14", "items": [{
            "description": "Professional service", "quantity": "1", "unit": "service",
            "unit_price": "100", "discount_percent": "0", "tax_rate": "18",
        }],
    })
    output = generate_invoice_pdf(database, business_id, bill_id, tmp_path / "attribution.pdf")
    text = "\n".join(page.extract_text() or "" for page in pypdf.PdfReader(str(output)).pages)
    assert "Generated by KoshFlow" in text
    assert "Invoice Preview Customer" in text
    assert "TAX INVOICE" in text


def test_thermal_receipt_pdf_generates_without_collapsed_columns(database, tmp_path):
    pypdf = pytest.importorskip("pypdf")
    from koshflow.services.bill_service import BillService
    from koshflow.services.pdf_service import generate_invoice_pdf
    from koshflow.services.setup_service import SetupService
    from tests.helpers import valid_setup

    user_id, business_id = SetupService(database).complete_setup(valid_setup())
    service = BillService(database)
    service.ensure_starter_templates(business_id)
    bill_id = service.create_bill(business_id, user_id, {
        "customer_type": "B2C", "document_type": "tax_invoice", "customer_name": "Thermal Receipt Customer",
        "invoice_date": "2026-10-14", "items": [{
            "description": "Tea and snacks", "quantity": "2", "unit": "each",
            "unit_price": "45", "discount_percent": "0", "tax_rate": "5",
            "hsn_sac": "2101",
        }],
    })
    thermal_template = next(
        template for template in service.list_templates(business_id)
        if template["template_name"] == "Market Receipt"
    )
    output = generate_invoice_pdf(
        database, business_id, bill_id, tmp_path / "market_receipt.pdf", thermal_template["template_id"]
    )
    reader = pypdf.PdfReader(str(output))
    page_text = "\n".join(page.extract_text() or "" for page in reader.pages)
    assert len(reader.pages) >= 1
    assert float(reader.pages[0].mediabox.width) == pytest.approx(80 * 72 / 25.4, abs=1.0)
    assert float(reader.pages[0].mediabox.height) < 230 * 72 / 25.4
    assert "Tea and snacks" in page_text
    assert "Generated by KoshFlow" in page_text
