def test_walk_in_customers_are_persisted_and_reused_without_phone(database):
    user_id, business_id = SetupService(database).complete_setup(valid_setup())
    service = CustomerService(database)

    first = service.resolve_or_create_for_sale(
        business_id, user_id,
        {"name": "Walk-in Customer", "phone": "", "customer_type": "individual"},
    )
    second = service.resolve_or_create_for_sale(
        business_id, user_id,
        {"name": "Walk-in Customer", "phone": "", "customer_type": "individual"},
    )

    rows = service.list_customers(business_id)
    assert first == second
    assert len([row for row in rows if row["name"] == "Walk-in Customer"]) == 1
    assert service.get_customer(business_id, first)["customer_code"] == "CUS-000001"


def test_named_walk_in_without_phone_is_saved_and_reused_by_exact_name(database):
    user_id, business_id = SetupService(database).complete_setup(valid_setup())
    service = CustomerService(database)
    values = {"name": "Counter Customer", "phone": "", "customer_type": "individual"}
    first = service.resolve_or_create_for_sale(business_id, user_id, values)
    second = service.resolve_or_create_for_sale(business_id, user_id, {**values, "name": "  COUNTER   CUSTOMER  "})
    assert first == second
    assert len(service.list_customers(business_id)) == 1


def test_invoice_profile_is_business_scoped_and_defaults_include_optional_payment_visibility(database):
    user_id, business_a = SetupService(database).complete_setup(valid_setup())
    business_b = "BIZ-unconfigured-other"
    save_invoice_profile(database, business_a, {
        "website": "example.com", "upi_id": "pay@upi", "show_bank": True,
        "show_upi": True, "show_qr": False,
    })
    profile_a = load_invoice_profile(database, business_a)
    profile_b = load_invoice_profile(database, business_b)
    assert profile_a["website"] == "https://example.com"
    assert profile_a["upi_id"] == "pay@upi"
    assert profile_a["show_bank"] is True and profile_a["show_qr"] is False
    assert profile_b["website"] == ""
    assert profile_b["upi_id"] == ""


def test_invoice_pdf_includes_saved_website_bank_and_upi_details(database, tmp_path):
    import pytest
    pypdf = pytest.importorskip("pypdf")
    user_id, business_id = SetupService(database).complete_setup(valid_setup())
    billing = BillService(database)
    billing.ensure_starter_templates(business_id)
    bill_id = billing.create_bill(business_id, user_id, {
        "customer_type": "B2C", "document_type": "tax_invoice", "customer_name": "Invoice Payment Customer",
        "invoice_date": "2026-10-14", "items": [{
            "description": "Notebook", "quantity": "2", "unit": "pcs",
            "unit_price": "25", "discount_percent": "0", "tax_rate": "0",
        }],
    })
    asset = Path(__file__).resolve().parents[1] / "assets" / "koshflow-mark.png"
    save_invoice_profile(database, business_id, {
        "website": "https://example.test", "logo_path": str(asset),
        "bank_account_name": "Example Trading House", "bank_name": "Sample Bank",
        "account_number": "1234567890", "ifsc": "SAMP0000123", "branch": "Bilaspur",
        "upi_id": "example@upi", "qr_code_path": str(asset),
        "show_bank": True, "show_upi": True, "show_qr": True,
    })
    output = generate_invoice_pdf(database, business_id, bill_id, tmp_path / "invoice-payment-details.pdf")
    text = "\n".join(page.extract_text() or "" for page in pypdf.PdfReader(str(output)).pages)
    assert output.exists() and output.stat().st_size > 0
    # The stored logo must be embedded in the rendered document, not silently omitted.
    reader = pypdf.PdfReader(str(output))
    assert len(reader.pages[0].images) >= 1
    assert "https://example.test" in text
    assert "Sample Bank" in text
    assert "1234567890" in text
    assert "SAMP0000123" in text
    assert "example@upi" in text
    assert "Generated by KoshFlow" in text


def test_invoice_logo_is_trimmed_and_keeps_its_wordmark_ratio(tmp_path):
    from PIL import Image, ImageDraw
    from koshflow.services.pdf_service import _cropped_logo_stream

    logo = Image.new("RGB", (900, 280), "white")
    draw = ImageDraw.Draw(logo)
    draw.rectangle((180, 68, 730, 200), fill="black")
    path = tmp_path / "wide-wordmark.png"
    logo.save(path)
    prepared = _cropped_logo_stream(path, 102.0, 42.0)
    assert prepared is not None
    stream, width, height = prepared
    assert width <= 102.0 and height <= 42.0
    assert width / height > 3.0
    assert stream.read(8) == b"\x89PNG\r\n\x1a\n"
